# --- bff.py -----------------------------------------------------------------------------------------------------------
def load_bffpy(algocell: Path):
    exp = (algocell / "experiments").resolve()
    if str(exp) not in sys.path:
        sys.path.insert(0, str(exp))
    import micro.bff as bffpy  # noqa: E402  (experiments/micro/bff.py, imported from the checkout)
    if Path(bffpy.__file__).resolve() != exp / "micro" / "bff.py":
        raise RuntimeError(f"imported {bffpy.__file__}, not {exp / 'micro' / 'bff.py'}")
    return bffpy


_W = None  # bff.py in a CPU worker


def _worker_init(algocell: str) -> None:
    global _W
    _W = load_bffpy(Path(algocell))


def _cpu_task(args):
    """reference_execute on a slice of a batch: pair_index is the pair's index in its batch (bff.py's gid.x)."""
    kw, pairs, i0, roll_seed, steps = args
    mem = np.empty_like(pairs)
    out = np.empty((pairs.shape[0], 4), dtype=np.uint32)
    for k in range(pairs.shape[0]):
        m, r = _W.reference_execute(pairs[k], steps, pair_index=i0 + k, roll_seed=roll_seed, **kw)
        mem[k] = m
        out[k] = (r["executed"], r["entered"], r["max_pc"], r["writesB"])
    return i0, mem, out


# --- Zilion -----------------------------------------------------------------------------------------------------------
def build_machines(configs: list[dict], tmp: Path) -> dict[str, tuple[str, dict]]:
    cfg = tmp / "configs.json"
    cfg.write_text(json.dumps(configs))
    node = os.environ.get("ZILION_NODE", "node")
    subprocess.run([node, str(HERE / "bff_machine.mjs"), str(cfg), str(tmp)], check=True)
    return {c["name"]: ((tmp / f"{c['name']}.wgsl").read_text(), json.loads((tmp / f"{c['name']}.manifest.json").read_text())) for c in configs}


def zilion_outputs(manifest: dict, rec: np.ndarray) -> dict:
    """bff.py's per-encounter record from a Zilion lane record (the mapping documented in docs/ARCHITECTURE.md)."""
    f = {x["name"]: x for x in manifest["record"]["fields"]}
    seg = f["writeCounts"]["items"]
    assert seg == ["A", "B"], seg  # no padding on the bff.py pair
    P = manifest["memory"]["ringBytes"]
    bits = lambda name: np.unpackbits(np.ascontiguousarray(rec[:, f[name]["offset"]: f[name]["offset"] + f[name]["words"]]).view(np.uint8),  # noqa: E731
                                      axis=1, bitorder="little")[:, :P].astype(bool)
    starts, fetched = bits("startMap"), bits("fetchMap")
    last = np.where(starts.any(1), P - 1 - np.argmax(starts[:, ::-1], axis=1), 0)
    return {
        "executed": rec[:, f["steps"]["offset"]],
        "entered": starts[:, TAPE:].any(1).astype(np.uint32),
        "max_pc": last.astype(np.uint32),
        "writesB": rec[:, f["writeCounts"]["offset"] + 1],
        "halt": rec[:, f["haltReason"]["offset"]],
        "trap": rec[:, f["trapCause"]["offset"]],
        "starts": starts,
        "fetched": fetched,
    }


_K = np.random.default_rng(7).integers(1, 1 << 63, size=36, dtype=np.uint64) | np.uint64(1)


def digest(out: np.ndarray, mem: np.ndarray) -> np.ndarray:
    """A 64-bit digest of each pair's outputs and memory (for comparing variants pair by pair without keeping them)."""
    row = np.concatenate([out.astype(np.uint32), np.ascontiguousarray(mem).view(np.uint32)], axis=1).astype(np.uint64)
    return (row * _K).sum(axis=1, dtype=np.uint64)


def as_out(o: dict) -> np.ndarray:
    return np.stack([o[k] for k in FIELDS], axis=1).astype(np.uint32)


# --- pairs ------------------------------------------------------------------------------------------------------------
def make_pairs(b: int, n: int, amap: np.ndarray) -> np.ndarray:
    rng = np.random.default_rng(20261010 + b)
    if b % 2 == 0:
        return rng.integers(0, 256, size=(n, PAIR), dtype=np.uint8)
    ops = sorted({int(x) for x in amap if x})
    by_op = [np.flatnonzero(amap == o).astype(np.uint8) for o in ops]
    kind = rng.random((n, PAIR))
    op = rng.integers(0, len(ops), size=(n, PAIR))
    pick = rng.integers(0, 1 << 16, size=(n, PAIR))
    inst = np.zeros((n, PAIR), dtype=np.uint8)
    for k, bs in enumerate(by_op):
        m = op == k
        inst[m] = bs[pick[m] % len(bs)]
    rand = rng.integers(0, 256, size=(n, PAIR), dtype=np.uint8)
    return np.where(kind < 0.55, inst, np.where(kind < 0.70, 0, rand)).astype(np.uint8)


# --- main parts -------------------------------------------------------------------------------------------------------
def run_variants(a, bffpy, alphabets, machines, pool) -> tuple[list[dict], bool]:
    rows, ok = [], True
    nb = a.pairs // a.batch
    done = {}
    if a.partial and Path(a.partial).exists():  # rows of an interrupted run with the same settings and the same WGSL
        for line in Path(a.partial).read_text().splitlines():
            r = json.loads(line)
            if (r["settings"] == settings_of(a) and r["variant"] in machines
                    and r["wgsl_sha256"] == hashlib.sha256(machines[r["variant"]][0].encode()).hexdigest()):
                done[r["variant"]] = r
    for name, kw0 in VARIANTS:
        if a.only and a.only not in name:
            continue
        if name in done:
            rows.append(done[name])
            ok &= done[name]["ok"]
            print(f"  {'ok  ' if done[name]['ok'] else 'FAIL'}  {name}: from {a.partial} ({done[name]['z_vs_gpu']}/{done[name]['pairs']} identical)", flush=True)
            continue
        kw = dict(kw0)
        if isinstance(kw.get("alphabet"), str):
            kw["alphabet"] = alphabets[kw["alphabet"]]
        g = bffpy.BFF(max_pairs=a.batch, steps=STEPS, **kw)
        amap = g.alphabet
        wgsl, manifest = machines[name]
        z = Machine(wgsl, manifest)
        dial = 0.0 < kw.get("halt_p", 1.0) < 1.0 and not kw.get("nohalt")
        if dial:  # bff.py's always-halt and never-halt kernels on the same pairs, for the both-outcomes count
            g_hi = bffpy.BFF(max_pairs=a.batch, steps=STEPS, **{**kw, "halt_p": 1.0})
            g_lo = bffpy.BFF(max_pairs=a.batch, steps=STEPS, **{**kw, "nohalt": True})
        t0 = time.time()
        acc = {"pairs": 0, "cpu_pairs": 0, "z_vs_gpu": 0, "z_vs_cpu": 0, "gpu_vs_cpu": 0, "mem_eq": 0,
               "field_eq": {k: 0 for k in FIELDS}, "budget": 0, "bounds": 0, "unmatched": 0, "running_other": 0,
               "entered": 0, "writesB_pos": 0, "mem_changed": 0, "partner_changed": 0, "steps_sum": 0, "writesB_sum": 0,
               "fetch_eq_start": 0, "fetch_entered_differs": 0, "start_subset_fetch": 0, "steps_hist": np.zeros(5, dtype=np.int64)}
        if dial:
            acc["dial_both_outcomes"] = 0
        for b in range(nb):
            pairs = make_pairs(b, a.batch, amap)
            seed = 1 + b
            ncpu = int(round(a.cpu * a.batch))
            cpu_job = None
            if ncpu:
                chunk = 512
                tasks = [(kw, pairs[i: min(i + chunk, ncpu)], i, seed, STEPS) for i in range(0, ncpu, chunk)]
                cpu_job = pool.map_async(_cpu_task, tasks)
            g_mem, g_out = g.execute(pairs, roll_seed=seed)
            z_mem, z_rec = z.run(pairs, seed=seed, budget=STEPS)
            zo = zilion_outputs(manifest, z_rec)
            z_out = as_out(zo)
            same_zg = np.all(z_mem == g_mem, axis=1) & np.all(z_out == g_out, axis=1)
            acc["z_vs_gpu"] += int(same_zg.sum())
            acc["mem_eq"] += int(np.all(z_mem == g_mem, axis=1).sum())
            for k, fld in enumerate(FIELDS):
                acc["field_eq"][fld] += int((z_out[:, k] == g_out[:, k]).sum())
            if cpu_job is not None:
                c_mem = np.empty((ncpu, PAIR), dtype=np.uint8)
                c_out = np.empty((ncpu, 4), dtype=np.uint32)
                for i0, m, o in cpu_job.get():
                    c_mem[i0: i0 + m.shape[0]] = m
                    c_out[i0: i0 + m.shape[0]] = o
                acc["z_vs_cpu"] += int((np.all(z_mem[:ncpu] == c_mem, axis=1) & np.all(z_out[:ncpu] == c_out, axis=1)).sum())
                acc["gpu_vs_cpu"] += int((np.all(g_mem[:ncpu] == c_mem, axis=1) & np.all(g_out[:ncpu] == c_out, axis=1)).sum())
                acc["cpu_pairs"] += ncpu
            acc["pairs"] += a.batch
            # how the encounters ended (Zilion's record; the outputs above are equal, so it describes bff.py's too)
            ex = zo["executed"].astype(np.int64)
            acc["budget"] += int((ex == STEPS).sum())
            acc["bounds"] += int((zo["trap"] == 4).sum())
            acc["unmatched"] += int((zo["trap"] == 3).sum())
            acc["running_other"] += int(((zo["trap"] == 0) & (ex != STEPS)).sum())
            acc["entered"] += int(zo["entered"].sum())
            acc["writesB_pos"] += int((zo["writesB"] > 0).sum())
            acc["mem_changed"] += int(np.any(z_mem != pairs, axis=1).sum())
            acc["partner_changed"] += int(np.any(z_mem[:, TAPE:] != pairs[:, TAPE:], axis=1).sum())
            acc["steps_sum"] += int(ex.sum())
            acc["writesB_sum"] += int(zo["writesB"].astype(np.int64).sum())
            acc["steps_hist"] += np.histogram(ex, bins=[1, 128, 129, 1024, STEPS, STEPS + 1])[0]
            acc["fetch_eq_start"] += int(np.all(zo["fetched"] == zo["starts"], axis=1).sum())
            acc["start_subset_fetch"] += int(np.all(~zo["starts"] | zo["fetched"], axis=1).sum())
            acc["fetch_entered_differs"] += int((zo["fetched"][:, TAPE:].any(1) != zo["starts"][:, TAPE:].any(1)).sum())
            if dial:  # a lane whose result differs from both drew a continue (first unmatched bracket) and a halt
                d = digest(z_out, z_mem)
                d_hi = digest(*g_hi.execute(pairs, roll_seed=seed)[::-1])
                d_lo = digest(*g_lo.execute(pairs, roll_seed=seed)[::-1])
                acc["dial_both_outcomes"] += int(((d != d_hi) & (d != d_lo)).sum())
            print(f"    {name} batch {b + 1}/{nb}: {int(same_zg.sum())}/{a.batch} identical to bff.py GPU"
                  + (f", CPU {ncpu} pairs" if ncpu else ""), file=sys.stderr, flush=True)
        n = acc["pairs"]
        literal = bool(kw.get("literal"))
        good = acc["z_vs_gpu"] == n and acc["z_vs_cpu"] == acc["cpu_pairs"] and acc["gpu_vs_cpu"] == acc["cpu_pairs"]
        good = good and (acc["start_subset_fetch"] == n) and (literal or acc["fetch_eq_start"] == n)
        ok &= good
        row = {"variant": name, "bffpy_args": {k: (v if not isinstance(v, np.ndarray) else kw0["alphabet"]) for k, v in kw.items()},
               "ok": bool(good), "seconds": round(time.time() - t0, 1), "settings": settings_of(a),
               "wgsl_sha256": hashlib.sha256(wgsl.encode()).hexdigest(),
               **{k: (v.tolist() if isinstance(v, np.ndarray) else v) for k, v in acc.items()}}
        rows.append(row)
        if a.partial:
            with open(a.partial, "a") as fh:
                fh.write(json.dumps(row) + "\n")
        print(f"  {'ok  ' if good else 'FAIL'}  {name}: Zilion = bff.py GPU on {acc['z_vs_gpu']}/{n}, Zilion = CPU on "
              f"{acc['z_vs_cpu']}/{acc['cpu_pairs']}, GPU = CPU on {acc['gpu_vs_cpu']}/{acc['cpu_pairs']} ({row['seconds']} s)", flush=True)
    return rows, ok


def settings_of(a) -> dict:
    return {"pairs": a.pairs, "batch": a.batch, "cpu": a.cpu, "steps": STEPS}


def run_mutants(a, bffpy, machines, rows_by_name) -> tuple[list[dict], bool]:
    out, ok = [], True
    b = 1  # an op-rich batch
    for k, (label, base, _, _, seed_off) in enumerate(MUTANTS):
        kw = dict(VARIANTS[[v[0] for v in VARIANTS].index(base)][1])
        g = bffpy.BFF(max_pairs=a.batch, steps=STEPS, **kw)
        pairs = make_pairs(b, a.batch, g.alphabet)
        seed = 1 + b
        g_mem, g_out = g.execute(pairs, roll_seed=seed)
        wgsl, manifest = machines[f"mutant{k}"]
        z_mem, z_rec = Machine(wgsl, manifest).run(pairs, seed=seed + seed_off, budget=STEPS)
        z_out = as_out(zilion_outputs(manifest, z_rec))
        differ = int((np.any(z_mem != g_mem, axis=1) | np.any(z_out != g_out, axis=1)).sum())
        caught = differ > 0
        ok &= caught
        out.append({"mutant": label, "base": base, "pairs": a.batch, "differ": differ, "caught": caught})
        print(f"  {'ok  ' if caught else 'FAIL'}  negative control '{label}' on {base}: {differ}/{a.batch} pairs differ", flush=True)
    return out, ok


class Ledger:
    def __init__(self):
        self.calls = self.pairs = self.z_gpu = self.z_cpu = self.gpu_cpu = 0
        self.configs: set = set()


def run_kernel_tests(a, bffpy, tmp: Path) -> tuple[dict, bool]:
    """bff.py's own test suite under pytest, with every BFF.execute mirrored on Zilion and on reference_execute."""
    import pytest  # noqa: E402

    ledger = Ledger()
    cache: dict = {}

    class MirrorBFF(bffpy.BFF):
        def __init__(self, *args, **kw):
            super().__init__(*args, **kw)
            self.cfg = {"steps": self.steps, "ip_wrap": bool(self.ip_wrap), "literal": bool(self.literal), "nohalt": bool(self.nohalt),
                        "halt_p": self.halt_p, "lit_rep": self.lit_rep, "alphabet": [int(x) for x in self.alphabet]}
            key = json.dumps(self.cfg, sort_keys=True)
            if key not in cache:
                name = f"kt{len(cache)}"
                wgsl, manifest = build_machines([{"name": name, **self.cfg}], tmp)[name]
                cache[key] = (Machine(wgsl, manifest), manifest)
            self.zm, self.zmanifest = cache[key]
            ledger.configs.add(key)

        def execute(self, pairs, steps=None, roll_seed=None):
            mem, out = super().execute(pairs, steps, roll_seed)
            seed = roll_seed if roll_seed is not None else self._rolls
            steps = self.steps if steps is None else steps
            p = np.ascontiguousarray(pairs, dtype=np.uint8)
            z_mem, z_rec = self.zm.run(p, seed=seed, budget=steps)
            z_out = as_out(zilion_outputs(self.zmanifest, z_rec))
            c_mem = np.empty_like(p)
            c_out = np.empty((p.shape[0], 4), dtype=np.uint32)
            for i in range(p.shape[0]):
                m, r = bffpy.reference_execute(p[i], steps, ip_wrap=self.ip_wrap, alphabet=self.alphabet, literal=self.literal, nohalt=self.nohalt,
                                               halt_p=self.halt_p, lit_rep=self.lit_rep, pair_index=i, roll_seed=seed)
                c_mem[i] = m
                c_out[i] = (r["executed"], r["entered"], r["max_pc"], r["writesB"])
            ledger.calls += 1
            ledger.pairs += p.shape[0]
            ledger.z_gpu += int((np.all(z_mem == mem, axis=1) & np.all(z_out == out, axis=1)).sum())
            ledger.z_cpu += int((np.all(z_mem == c_mem, axis=1) & np.all(z_out == c_out, axis=1)).sum())
            ledger.gpu_cpu += int((np.all(mem == c_mem, axis=1) & np.all(out == c_out, axis=1)).sum())
            return mem, out

    class Mirror:
        """pytest plugin: replace the BFF class the test module imported with the mirroring subclass."""

        def __init__(self):
            self.passed = self.failed = 0

        @pytest.hookimpl(tryfirst=True)
        def pytest_runtest_setup(self, item):
            item.module.BFF = MirrorBFF

        def pytest_runtest_logreport(self, report):
            if report.when == "call":
                self.passed += report.passed
                self.failed += report.failed

    plugin = Mirror()
    test_file = a.algocell / "experiments" / "tests" / "test_bff.py"
    code = pytest.main([str(test_file), "-q", "-p", "no:cacheprovider", "--rootdir", str(tmp), "-c", os.devnull], plugins=[plugin])
    res = {"file": "experiments/tests/test_bff.py", "pytest_exit": int(code), "passed": plugin.passed, "failed": plugin.failed,
           "execute_calls": ledger.calls, "pairs": ledger.pairs, "configs": len(ledger.configs),
           "z_vs_gpu": ledger.z_gpu, "z_vs_cpu": ledger.z_cpu, "gpu_vs_cpu": ledger.gpu_cpu}
    good = code == 0 and plugin.failed == 0 and plugin.passed > 0 and ledger.pairs > 0 and ledger.z_gpu == ledger.z_cpu == ledger.gpu_cpu == ledger.pairs
    print(f"  {'ok  ' if good else 'FAIL'}  bff.py's kernel tests: {plugin.passed} passed, {plugin.failed} failed; {ledger.calls} execute calls "
          f"({ledger.pairs} pairs, {len(ledger.configs)} configurations) mirrored: Zilion = GPU on {ledger.z_gpu}, Zilion = CPU on "
          f"{ledger.z_cpu}, GPU = CPU on {ledger.gpu_cpu}", flush=True)
    return res, good


def run_dial_probe(a, bffpy, machines) -> tuple[dict, bool]:
    """The world's draw at (seed, lane, step) read back from the GPU, against bff.py's hash32 and bracket_halts."""
    wgsl, manifest = machines["probe"]
    m = Machine(wgsl, manifest)
    n = 1 << 14 if a.quick else 1 << 16
    C1, C2, M = 0x9E3779B1, 0x85EBCA77, 0xFFFFFFFF
    seeds = [0, 1, 0xDEADBEEF, M]
    steps = [0, 1, 4096, STEPS - 1, (1 << 31) + 5, M]
    lanes = [0, 1 << 20, (1 << 32) - n]
    ps = [0.5, 0.3, 0.1, 0.03, 0.01]
    draws = equal = 0
    dec_equal = {p: 0 for p in ps}
    dec_true = {p: 0 for p in ps}
    for seed in seeds:
        for s in steps:
            for l0 in lanes:
                mem, _ = m.run(np.zeros((n, 4), dtype=np.uint8), seed=seed, budget=1, lane_base=l0, step_base=s)
                d = mem.view("<u4").reshape(n)
                for i in range(n):
                    p = l0 + i
                    ref = bffpy.hash32(((p * C1) & M) ^ (((s + 1) * C2) & M) ^ (seed & M))
                    draws += 1
                    equal += int(d[i]) == ref
                if s < STEPS:  # bracket_halts over the pair indices of one bff.py dispatch
                    for p_ in ps:
                        q = int(round(p_ * 4294967296.0))
                        t = threshold_from_wgsl(p_, machines)
                        for i in range(0, n, 16):
                            bh = bffpy.bracket_halts(l0 + i, s, False, q, seed)
                            dec_equal[p_] += bh == (int(d[i]) < t)
                            dec_true[p_] += bh
    checked = sum(1 for seed in seeds for s in steps if s < STEPS for l0 in lanes for i in range(0, n, 16))
    res = {"draws": draws, "equal": equal, "seeds": seeds, "steps": steps, "lane_bases": lanes, "lanes_per_run": n,
           "bracket_halts": {str(p): {"checked": checked, "equal": dec_equal[p], "halt_fraction": round(dec_true[p] / checked, 4)} for p in ps}}
    good = equal == draws and all(dec_equal[p] == checked for p in ps)
    print(f"  {'ok  ' if good else 'FAIL'}  dial hash: zil_draw(0) = bff.py hash32(p*C1 ^ (s+1)*C2 ^ roll_seed) on {equal}/{draws} draws "
          f"(seeds {len(seeds)}, step indices {len(steps)}, lane bases {len(lanes)}); bracket_halts = (draw < threshold) on "
          + ", ".join(f"p={p}: {dec_equal[p]}/{checked}" for p in ps), flush=True)
    return res, good


_THRESHOLDS: dict = {}


def threshold_from_wgsl(p: float, machines) -> int:
    """The dial threshold the generated WGSL compares the draw with, for a dial machine of probability p."""
    if p not in _THRESHOLDS:
        wgsl, _ = machines[f"thr{p}"]
        found = re.findall(r"zil_draw\(0x0u\) < 0x([0-9a-f]+)u", wgsl)
        assert len(found) == 1, found
        _THRESHOLDS[p] = int(found[0], 16)
    return _THRESHOLDS[p]


def git(*args, cwd: Path) -> str:
    try:
        return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:  # noqa: BLE001
        return "?"


def write_report(path: Path, rep: dict) -> None:
    path.with_suffix(".json").write_text(json.dumps(rep, indent=1) + "\n")
    pc = lambda x, n: f"{100.0 * x / n:.1f}%" if n else "-"  # noqa: E731
    L = [f"# BFF equivalence: Zilion against Algocell's bff.py",
         "",
         f"Generated by `test/world/bff_equiv.py` ({rep['generated']}). Do not edit; rerun it.",
         "",
         f"- Zilion {rep['zilion']['commit']}{' (modified)' if rep['zilion']['dirty'] else ''}, BFF core {rep['zilion']['core']}",
         f"- bff.py: `experiments/micro/bff.py` at Algocell {rep['bffpy']['commit']}, sha256 `{rep['bffpy']['sha256']}`"
         + (" (modified in the checkout)" if rep["bffpy"]["dirty"] else ""),
         f"- {rep['adapter']}; Python {rep['python']}, numpy {rep['numpy']}, wgpu {rep['wgpu']}",
         f"- {rep['pairs_per_variant']:,} pairs per variant ({rep['batches']} batches of {rep['batch']:,}: even batches uniform random bytes, odd "
         f"batches op-rich), {STEPS} steps per encounter, roll_seed 1 + batch; CPU reference on {rep['cpu_fraction'] * 100:g}% of every batch",
         "",
         "Compared on every pair: final memory, `executed` (record `steps`), `entered` (start map ∩ [64, 128)), `max_pc` "
         "(highest start-map position) and `writesB` (write counter of segment B).",
         "",
         "## Variants",
         "",
         "| variant | bff.py arguments | pairs | Zilion = bff.py GPU | Zilion = CPU ref | GPU = CPU ref | mean steps | ran to budget | left tape | unmatched halt | entered B | wrote B | memory changed |",
         "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rep["variants"]:
        n = r["pairs"]
        args = ", ".join(f"{k}={v}" for k, v in r["bffpy_args"].items()) or "(published)"
        L.append(f"| {r['variant']} | {args} | {n:,} | {r['z_vs_gpu']:,} | {r['z_vs_cpu']:,}/{r['cpu_pairs']:,} | {r['gpu_vs_cpu']:,}/{r['cpu_pairs']:,} | "
                 f"{r['steps_sum'] / n:.0f} | {pc(r['budget'], n)} | {pc(r['bounds'], n)} | {pc(r['unmatched'], n)} | {pc(r['entered'], n)} | "
                 f"{pc(r['writesB_pos'], n)} | {pc(r['mem_changed'], n)} |")
    dials = [r for r in rep["variants"] if "dial_both_outcomes" in r]
    if dials:
        L += ["", "Dials: a lane whose result differs from both bff.py's always-halt (halt_p = 1) and never-halt (nohalt) kernels on "
              "the same pairs drew both outcomes (a continue at its first unmatched bracket, a halt later).", "",
              "| dial | pairs | halted on an unmatched bracket | drew both outcomes |", "|---|---:|---:|---:|"]
        for r in dials:
            L.append(f"| {r['variant']} | {r['pairs']:,} | {r['unmatched']:,} | {r['dial_both_outcomes']:,} |")
    L += ["", "Steps per encounter (all variants): " + "; ".join(
        f"{r['variant']} [1–127: {r['steps_hist'][0]:,}, 128: {r['steps_hist'][1]:,}, 129–1023: {r['steps_hist'][2]:,}, 1024–8191: {r['steps_hist'][3]:,}, 8192: {r['steps_hist'][4]:,}]"
        for r in rep["variants"]), "",
          "Fetch map: equal to the start map on every pair of the variants without the literal push; with it, a superset "
          "(the push fetches its two operand bytes). `entered` read from the fetch map instead would differ on: " + ", ".join(
              f"{r['variant']} {r['fetch_entered_differs']:,}" for r in rep["variants"] if r["bffpy_args"].get("literal")) + " pairs.", ""]
    L += ["## Negative controls", "", "Mutated Zilion machines on one op-rich batch; each must disagree with bff.py.", "",
          "| mutant | on | pairs differing |", "|---|---|---:|"]
    for m in rep["mutants"]:
        L.append(f"| {m['mutant']} | {m['base']} | {m['differ']:,}/{m['pairs']:,} |")
    k = rep.get("kernel_tests")
    if k:
        L += ["", "## bff.py's own kernel tests", "",
              f"`{k['file']}` under pytest with every `BFF.execute` mirrored on Zilion and on `reference_execute`: {k['passed']} passed, "
              f"{k['failed']} failed; {k['execute_calls']} execute calls, {k['pairs']:,} pairs, {k['configs']} configurations; Zilion = bff.py GPU on "
              f"{k['z_vs_gpu']:,}, Zilion = CPU on {k['z_vs_cpu']:,}, GPU = CPU on {k['gpu_vs_cpu']:,}."]
    d = rep.get("dial_probe")
    if d:
        L += ["", "## The dial hash", "",
              f"`zil_draw(0)` read back from the GPU (a raw `on_instruction_start` hook writes it into memory) equals bff.py's "
              f"`hash32(p·0x9E3779B1 ^ (s+1)·0x85EBCA77 ^ roll_seed)` on {d['equal']:,}/{d['draws']:,} draws (seeds {', '.join(hex(x) for x in d['seeds'])}; "
              f"step indices {', '.join(str(x) for x in d['steps'])}; lanes from {', '.join(str(x) for x in d['lane_bases'])}, {d['lanes_per_run']:,} each).",
              "", "bff.py's `bracket_halts(p, s, nohalt=False, halt_q, roll_seed)` against the generated WGSL's `zil_draw(0) < threshold`:", "",
              "| halt_p | bff.py halt_q | Zilion threshold | decisions equal | halt fraction |", "|---:|---:|---:|---:|---:|"]
        for p, v in d["bracket_halts"].items():
            t = rep["thresholds"][p]
            L.append(f"| {p} | {t['halt_q']:#x} | {t['zilion']:#x} | {v['equal']:,}/{v['checked']:,} | {v['halt_fraction']} |")
    parts = [k for k, v in (("variants", rep["variants"]), ("negative controls", rep["mutants"]), ("kernel tests", rep.get("kernel_tests")),
                                ("dial probe", rep.get("dial_probe"))) if not v]
    L += ["", f"**Result: {'all identical, every negative control caught' if rep['ok'] else 'FAILED'}"
          + (f" (not run: {', '.join(parts)})" if parts else "") + ".**", ""]
    path.with_suffix(".md").write_text("\n".join(L))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--algocell", default=os.environ.get("ALGOCELL_DIR", str(ROOT.parent / "algocell")))
    ap.add_argument("--pairs", type=int, default=1 << 20)
    ap.add_argument("--batch", type=int, default=1 << 16)
    ap.add_argument("--cpu", type=float, default=1.0, help="fraction of every batch also run on reference_execute")
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--only", default="")
    ap.add_argument("--quick", action="store_true", help="a small smoke run (no report unless --report is given)")
    ap.add_argument("--skip", default="", help="comma list of parts to skip: variants, mutants, kernel, probe")
    ap.add_argument("--report", default="")
    ap.add_argument("--partial", default="", help="JSON lines of finished variants: appended to, and reused when rerun with the same settings")
    a = ap.parse_args()
    a.algocell = Path(a.algocell).resolve()
    if a.quick:
        a.pairs, a.batch = min(a.pairs, 1 << 13), min(a.batch, 1 << 12)
    if a.pairs % a.batch:
        ap.error("--pairs must be a multiple of --batch")
    skip = set(filter(None, a.skip.split(",")))
    bff_path = a.algocell / "experiments" / "micro" / "bff.py"
    if not bff_path.exists():
        print(f"no Algocell checkout at {a.algocell}; skipped")
        return 0
    bffpy = load_bffpy(a.algocell)
    alphabets = {"d2": bffpy.density_map(2, seed=0), "d4": bffpy.density_map(4, seed=0)}
    ok = True

    with tempfile.TemporaryDirectory(prefix="zilion-bff-") as td:
        tmp = Path(td)
        configs = []

        def cfg_of(name: str, kw0: dict) -> dict:
            kw = dict(kw0)
            if isinstance(kw.get("alphabet"), str):
                kw["alphabet"] = alphabets[kw["alphabet"]]
            amap = kw.get("alphabet")
            amap = bffpy.ascii_map(kw.get("literal", False)) if amap is None else amap
            return {"name": name, "steps": STEPS, "ip_wrap": kw.get("ip_wrap", False), "literal": kw.get("literal", False),
                    "nohalt": kw.get("nohalt", False), "halt_p": kw.get("halt_p", 1.0), "lit_rep": kw.get("lit_rep", 1),
                    "alphabet": [int(x) for x in amap]}

        var_kw = dict(VARIANTS)
        configs += [cfg_of(n, kw) for n, kw in VARIANTS]
        for k, (_, base, mut, salt, _) in enumerate(MUTANTS):
            c = cfg_of(f"mutant{k}", var_kw[base])
            c["mutate"] = mut
            if salt is not None:
                c["salt"] = salt
            configs.append(c)
        ps = [0.5, 0.3, 0.1, 0.03, 0.01]
        configs += [cfg_of(f"thr{p}", {"halt_p": p}) for p in ps]
        configs.append({"name": "probe", "probe": True})
        machines = build_machines(configs, tmp)
        thresholds = {str(p): {"halt_q": int(round(p * 4294967296.0)), "zilion": threshold_from_wgsl(p, machines)} for p in ps}
        for p, t in thresholds.items():
            if t["halt_q"] != t["zilion"]:
                ok = False
                print(f"  FAIL  dial threshold for p = {p}: bff.py halt_q {t['halt_q']:#x}, Zilion {t['zilion']:#x}")
        # bff.py's own halt_q (computed by its constructor) must agree with the formula used above
        for p in ps:
            assert bffpy.BFF(max_pairs=64, halt_p=p).halt_q == thresholds[str(p)]["halt_q"]

        rep = {"generated": time.strftime("%Y-%m-%d %H:%M:%S %Z"), "ok": None,
               "zilion": {"commit": git("rev-parse", "--short", "HEAD", cwd=ROOT), "dirty": bool(git("status", "--porcelain", "src", cwd=ROOT)),
                          "core": machines["std"][1]["core"]["coreVersion"]},
               "bffpy": {"sha256": hashlib.sha256(bff_path.read_bytes()).hexdigest(),
                         "commit": git("log", "-1", "--format=%h", "--", "experiments/micro/bff.py", cwd=a.algocell),
                         "dirty": bool(git("status", "--porcelain", "experiments/micro/bff.py", cwd=a.algocell))},
               "adapter": adapter_summary(), "python": platform.python_version(), "numpy": np.__version__,
               "wgpu": __import__("wgpu").__version__, "pairs_per_variant": a.pairs, "batch": a.batch, "batches": a.pairs // a.batch,
               "cpu_fraction": a.cpu, "thresholds": thresholds}

        if "variants" not in skip:
            ctx = mp.get_context("spawn")
            with ctx.Pool(a.workers, initializer=_worker_init, initargs=(str(a.algocell),)) as pool:
                rows, good = run_variants(a, bffpy, alphabets, machines, pool)
            rep["variants"] = rows
            ok &= good
        else:
            rep["variants"] = []
        if "mutants" not in skip:
            rep["mutants"], good = run_mutants(a, bffpy, machines, {r["variant"]: r for r in rep["variants"]})
            ok &= good
        else:
            rep["mutants"] = []
        if "kernel" not in skip:
            rep["kernel_tests"], good = run_kernel_tests(a, bffpy, tmp)
            ok &= good
        if "probe" not in skip:
            rep["dial_probe"], good = run_dial_probe(a, bffpy, machines)
            ok &= good
        rep["ok"] = bool(ok)
        if a.report:
            write_report(Path(a.report), rep)
            print(f"report: {a.report}.md, {a.report}.json")
    print(f"BFF equivalence: {'all identical' if ok else 'FAILED'} on {adapter_summary()}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
