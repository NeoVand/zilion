"""The WGSL test host that wraps a core for per-instruction vectors.

One invocation ("lane") runs one test: load the state record, run `steps` core steps, store the state record.
The host provides the memory and I/O hooks the core calls (mem_read, mem_write, io_read, io_write); the adapter
provides the core text, any other hooks it needs, zt_load_state / zt_store_state, and the step call.

Memory models (`mode`):
  sparse  per-lane table of (address, word) in a storage buffer; word = value | READABLE | WRITTEN. The table is
          pre-filled with every address the vector lists (initial RAM union final RAM); a write anywhere else is
          appended (a stray write). Linear search; any address width.
  full    a whole 64 KiB per lane plus READABLE/WRITTEN bitmaps, in a storage buffer cleared before the dispatch.
          The listed entries are scattered in before the run and gathered back into the same table after it, and
          the WRITTEN bitmap is scanned for stray writes, so both models return identical tables (the stray-write
          entries aside, which are appended in write order by `sparse` and in address order by `full`).
In both, a read of an address that is neither listed in the initial RAM nor written earlier in the run sets
ST_UNLISTED_READ and returns 0.

Bindings (group 0): 0 uniform params {count, steps, 0, 0}; 1 state_in (read); 2 state_out; 3 mem table;
4 port tables; 5 status; 6 full memory (full mode only).
"""

from __future__ import annotations

from dataclasses import dataclass

from .model import (
    CONSUMED,
    READABLE,
    ST_MEM_OVERFLOW,
    ST_PORT_OVERFLOW,
    ST_STRAY_WRITE,
    ST_UNLISTED_PORT,
    ST_UNLISTED_READ,
    WRITTEN,
)

FULL_BYTES_WORDS = 16384  # 64 KiB packed four bytes per u32
FULL_BITMAP_WORDS = 2048  # 65536 bits
FULL_STRIDE = FULL_BYTES_WORDS + 2 * FULL_BITMAP_WORDS  # bytes, READABLE bits, WRITTEN bits
STATUS_WORDS = 4


@dataclass(frozen=True)
class HostLayout:
    state_words: int
    mem_cap: int  # table slots per lane (listed addresses + room for stray writes)
    port_cap: int  # port slots per lane, for reads and for writes each
    addr_bits: int
    mode: str  # "sparse" | "full"

    @property
    def mem_stride(self) -> int:
        return 1 + 2 * self.mem_cap

    @property
    def port_stride(self) -> int:
        return 2 + 4 * self.port_cap

    @property
    def bindings(self) -> list[str]:
        b = ["uniform", "read-only-storage", "storage", "storage", "storage", "storage"]
        return b + (["storage"] if self.mode == "full" else [])


def build_host(layout: HostLayout, core: str, glue: str, step_call: str) -> str:
    if layout.mode not in ("sparse", "full"):
        raise ValueError(f"unknown memory mode {layout.mode!r}")
    if layout.mode == "full" and layout.addr_bits > 16:
        raise ValueError("full memory mode covers 16-bit address spaces only; use sparse")
    addr_mask = (1 << layout.addr_bits) - 1
    common = f"""
// ===== Zilion vector-test host ({layout.mode} memory) — generated by tools/ztest/vectors/host.py =====
const ZT_STATE_WORDS: u32 = {layout.state_words}u;
const ZT_MEM_CAP: u32 = {layout.mem_cap}u;
const ZT_MEM_STRIDE: u32 = {layout.mem_stride}u;
const ZT_PORT_CAP: u32 = {layout.port_cap}u;
const ZT_PORT_STRIDE: u32 = {layout.port_stride}u;
const ZT_ADDR_MASK: u32 = {addr_mask:#x}u;
const ZT_READABLE: u32 = {READABLE:#x}u;
const ZT_WRITTEN: u32 = {WRITTEN:#x}u;
const ZT_CONSUMED: u32 = {CONSUMED:#x}u;
const ZT_NONE: u32 = 0xffffffffu;
const ZT_ST_UNLISTED_READ: u32 = {ST_UNLISTED_READ}u;
const ZT_ST_STRAY_WRITE: u32 = {ST_STRAY_WRITE}u;
const ZT_ST_MEM_OVERFLOW: u32 = {ST_MEM_OVERFLOW}u;
const ZT_ST_UNLISTED_PORT: u32 = {ST_UNLISTED_PORT}u;
const ZT_ST_PORT_OVERFLOW: u32 = {ST_PORT_OVERFLOW}u;

struct ZtParams {{ count: u32, steps: u32, _p0: u32, _p1: u32 }};
@group(0) @binding(0) var<uniform> zt_params: ZtParams;
@group(0) @binding(1) var<storage, read> zt_state_in: array<u32>;
@group(0) @binding(2) var<storage, read_write> zt_state_out: array<u32>;
@group(0) @binding(3) var<storage, read_write> zt_mem: array<u32>;    // per lane: [n, (addr, word) x ZT_MEM_CAP]
@group(0) @binding(4) var<storage, read_write> zt_ports: array<u32>;  // per lane: [n_in, n_out, in (port, word) x CAP, out (port, value) x CAP]
@group(0) @binding(5) var<storage, read_write> zt_status: array<u32>; // per lane: [flags, first unlisted read, first stray write, first unlisted port]

var<private> zt_lane: u32;

// Set a status flag; the first occurrence of each flag records `a` in status word `slot`.
fn zt_flag(bit: u32, slot: u32, a: u32) {{
    let s = zt_lane * {STATUS_WORDS}u;
    if ((zt_status[s] & bit) == 0u && slot != 0u) {{ zt_status[s + slot] = a; }}
    zt_status[s] = zt_status[s] | bit;
}}

// Index of address `a` in this lane's table, or ZT_NONE.
fn zt_find(a: u32) -> u32 {{
    let b = zt_lane * ZT_MEM_STRIDE;
    let n = min(zt_mem[b], ZT_MEM_CAP);
    for (var i = 0u; i < n; i++) {{
        if (zt_mem[b + 1u + 2u * i] == a) {{ return i; }}
    }}
    return ZT_NONE;
}}

// Append a stray write (address outside the vector's lists) so its address and value are visible.
fn zt_append(a: u32, word: u32) {{
    let b = zt_lane * ZT_MEM_STRIDE;
    let n = zt_mem[b];
    if (n >= ZT_MEM_CAP) {{ zt_flag(ZT_ST_MEM_OVERFLOW, 0u, 0u); return; }}
    zt_mem[b + 1u + 2u * n] = a;
    zt_mem[b + 2u + 2u * n] = word;
    zt_mem[b] = n + 1u;
}}

// I/O hooks: reads consume the vector's listed (port, value) entries in order; writes are logged.
fn io_read(port: u32) -> u32 {{
    let b = zt_lane * ZT_PORT_STRIDE;
    let n = min(zt_ports[b], ZT_PORT_CAP);
    for (var i = 0u; i < n; i++) {{
        let k = b + 2u + 2u * i;
        if (zt_ports[k] == port && (zt_ports[k + 1u] & ZT_CONSUMED) == 0u) {{
            zt_ports[k + 1u] = zt_ports[k + 1u] | ZT_CONSUMED;
            return zt_ports[k + 1u] & 0xffu;
        }}
    }}
    zt_flag(ZT_ST_UNLISTED_PORT, 3u, port);
    return 0xffu;
}}

fn io_write(port: u32, val: u32) {{
    let b = zt_lane * ZT_PORT_STRIDE;
    let n = zt_ports[b + 1u];
    if (n >= ZT_PORT_CAP) {{ zt_flag(ZT_ST_PORT_OVERFLOW, 0u, 0u); return; }}
    let k = b + 2u + 2u * ZT_PORT_CAP + 2u * n;
    zt_ports[k] = port;
    zt_ports[k + 1u] = val & 0xffu;
    zt_ports[b + 1u] = n + 1u;
}}
"""
    if layout.mode == "sparse":
        memory = """
fn mem_read(addr: u32) -> u32 {
    let a = addr & ZT_ADDR_MASK;
    let i = zt_find(a);
    if (i != ZT_NONE) {
        let w = zt_mem[zt_lane * ZT_MEM_STRIDE + 2u + 2u * i];
        if ((w & (ZT_READABLE | ZT_WRITTEN)) != 0u) { return w & 0xffu; }
    }
    zt_flag(ZT_ST_UNLISTED_READ, 1u, a);
    return 0u;
}

fn mem_write(addr: u32, val: u32) {
    let a = addr & ZT_ADDR_MASK;
    let v = val & 0xffu;
    let i = zt_find(a);
    if (i != ZT_NONE) {
        let k = zt_lane * ZT_MEM_STRIDE + 2u + 2u * i;
        zt_mem[k] = (zt_mem[k] & ZT_READABLE) | ZT_WRITTEN | v;
        return;
    }
    zt_flag(ZT_ST_STRAY_WRITE, 2u, a);
    zt_append(a, ZT_WRITTEN | v);
}

fn zt_mem_begin() {}
fn zt_mem_end() {}
"""
    else:
        memory = f"""
@group(0) @binding(6) var<storage, read_write> zt_full: array<u32>; // per lane: bytes, READABLE bits, WRITTEN bits

const ZT_FULL_STRIDE: u32 = {FULL_STRIDE}u;
const ZT_FULL_RBITS: u32 = {FULL_BYTES_WORDS}u;
const ZT_FULL_WBITS: u32 = {FULL_BYTES_WORDS + FULL_BITMAP_WORDS}u;

fn zt_full_get(a: u32) -> u32 {{
    return (zt_full[zt_lane * ZT_FULL_STRIDE + (a >> 2u)] >> ((a & 3u) * 8u)) & 0xffu;
}}
fn zt_full_set(a: u32, v: u32) {{
    let k = zt_lane * ZT_FULL_STRIDE + (a >> 2u);
    let sh = (a & 3u) * 8u;
    zt_full[k] = (zt_full[k] & ~(0xffu << sh)) | ((v & 0xffu) << sh);
}}
fn zt_full_bit(region: u32, a: u32) -> bool {{
    return (zt_full[zt_lane * ZT_FULL_STRIDE + region + (a >> 5u)] & (1u << (a & 31u))) != 0u;
}}
fn zt_full_mark(region: u32, a: u32) {{
    let k = zt_lane * ZT_FULL_STRIDE + region + (a >> 5u);
    zt_full[k] = zt_full[k] | (1u << (a & 31u));
}}

fn mem_read(addr: u32) -> u32 {{
    let a = addr & ZT_ADDR_MASK;
    if (!zt_full_bit(ZT_FULL_RBITS, a) && !zt_full_bit(ZT_FULL_WBITS, a)) {{
        zt_flag(ZT_ST_UNLISTED_READ, 1u, a);
        return 0u;
    }}
    return zt_full_get(a);
}}

fn mem_write(addr: u32, val: u32) {{
    let a = addr & ZT_ADDR_MASK;
    zt_full_set(a, val);
    zt_full_mark(ZT_FULL_WBITS, a);
}}

// Scatter the listed initial RAM into this lane's (zeroed) 64 KiB.
fn zt_mem_begin() {{
    let b = zt_lane * ZT_MEM_STRIDE;
    let n = min(zt_mem[b], ZT_MEM_CAP);
    for (var i = 0u; i < n; i++) {{
        let w = zt_mem[b + 2u + 2u * i];
        if ((w & ZT_READABLE) != 0u) {{
            let a = zt_mem[b + 1u + 2u * i] & ZT_ADDR_MASK;
            zt_full_set(a, w);
            zt_full_mark(ZT_FULL_RBITS, a);
        }}
    }}
}}

// Gather the listed addresses back into the table, then append every written address outside it.
fn zt_mem_end() {{
    let b = zt_lane * ZT_MEM_STRIDE;
    let n = min(zt_mem[b], ZT_MEM_CAP);
    for (var i = 0u; i < n; i++) {{
        let a = zt_mem[b + 1u + 2u * i] & ZT_ADDR_MASK;
        let k = b + 2u + 2u * i;
        let wr = select(0u, ZT_WRITTEN, zt_full_bit(ZT_FULL_WBITS, a));
        zt_mem[k] = (zt_mem[k] & ZT_READABLE) | wr | zt_full_get(a);
    }}
    let wb = zt_lane * ZT_FULL_STRIDE + ZT_FULL_WBITS;
    for (var w = 0u; w < {FULL_BITMAP_WORDS}u; w++) {{
        var bits = zt_full[wb + w];
        while (bits != 0u) {{
            let bit = firstTrailingBit(bits);
            bits = bits & (bits - 1u);
            let a = w * 32u + bit;
            var listed = false;
            for (var i = 0u; i < n; i++) {{
                if ((zt_mem[b + 1u + 2u * i] & ZT_ADDR_MASK) == a) {{ listed = true; }}
            }}
            if (!listed) {{
                zt_flag(ZT_ST_STRAY_WRITE, 2u, a);
                zt_append(a, ZT_WRITTEN | zt_full_get(a));
            }}
        }}
    }}
}}
"""
    main = f"""
@compute @workgroup_size(64)
fn main(@builtin(global_invocation_id) gid: vec3u) {{
    let lane = gid.x;
    if (lane >= zt_params.count) {{ return; }}
    zt_lane = lane;
    zt_mem_begin();
    zt_load_state(lane * ZT_STATE_WORDS);
    for (var s = 0u; s < zt_params.steps; s++) {{
        {step_call}
    }}
    zt_store_state(lane * ZT_STATE_WORDS);
    zt_mem_end();
}}
"""
    return "\n".join([common, memory, "// ===== ISA glue (adapter) =====", glue, "// ===== core =====", core, main])
