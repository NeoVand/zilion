"""Markdown rendering of a vector ledger (test/baselines/<isa>-v<version>.md)."""

from __future__ import annotations

import json

from .report import flag_names, pct

# ISA-specific wording of the report: (what the architectural fields are, the internal columns, the group heading).
WORDING = {
    "z80": ("Architectural fields are the registers, F, R, I, IFF1/2, IM, memory and ports. WZ (MEMPTR), Q and the "
            "EI/P interrupt latches are internal and reported in their own columns.", "WZ, Q, EI/P", "prefix group"),
    "6502": ("Architectural fields are PC, S, A, X, Y, P, the halted state (JAM), memory, ports and the bus-write "
             "sequence (`bus`: every memory write in order, including the old-value write of a read-modify-write). "
             "There are no internal columns.", "none", "opcode group"),
}
FLAG_FIELD = {"z80": "f", "6502": "p"}


def _code(s: str) -> str:
    return f"`{s}`"


def _files(keys: list[str], limit: int = 40) -> str:
    shown = ", ".join(_code(k) for k in keys[:limit])
    return shown + (f", … ({len(keys)} files)" if len(keys) > limit else "")


def _reproducer(ex: dict, isa: str) -> list[str]:
    init = ex["initial"]
    regs = " ".join(f"{k}={v:#06x}" if k in ("pc", "sp", "ix", "iy", "wz", "af_", "bc_", "de_", "hl_") else f"{k}={v:#04x}"
                    for k, v in init.items())
    ram = " ".join(f"{a:04x}:{v:02x}" for a, v in ex["ram"])
    out = [
        f"- test `{ex['name']}` in file `{ex.get('file', '?')}`; instruction bytes `{ex['bytes']}`",
        f"- initial: `{regs}`",
        f"- initial RAM: `{ram}`" + (f"; ports: `{json.dumps(ex['ports'])}`" if ex.get("ports") else ""),
        "- divergence (expected vs Zilion):",
    ]
    for f, d in ex["diff"].items():
        mark = " **(unexpected bits " + d["unexpected_bits"] + ")**" if "unexpected_bits" in d else ""
        if f in ("mem", "ports", "bus"):
            body = {k: v for k, v in d.items() if k != "unexpected_bits"}
            out.append(f"  - `{f}`{mark}: `{json.dumps(body)}`")
        else:
            bits = flag_names(int(d["xor"], 16), isa, f) if f == FLAG_FIELD.get(isa, "f") else d["xor"]
            out.append(f"  - `{f}`: expected `{d['expected']}`, got `{d['actual']}` (xor `{d['xor']}`: {bits}){mark}")
    rerun = f"python -I tools/zt.py vectors {isa} <vector dir> --files '{ex.get('file', '?')}' --test '{ex['name']}'"
    out.append(f"- re-run: `{rerun}`")
    return out


def render(doc: dict, run: dict, digest: str, analysis: str | None) -> str:
    isa = doc["isa"]
    prov = doc["provenance"]
    t = doc["summary"]["totals"]
    h = doc["harness"]
    vec = doc["vectors"]
    L: list[str] = []
    w = L.append
    w(f"# {isa.upper()} per-instruction vector baseline: Zilion {prov['package']['version']}")
    w("")
    w("Generated by `tools/zt.py vectors` (docs/TESTING.md). The tables and reproducers below are generated from the "
      "ledger; the Analysis section is included from a hand-written file. The machine-readable ledger is the JSON "
      "file of the same name.")
    w("")
    w("## Provenance")
    w("")
    w("| | |")
    w("|---|---|")
    w(f"| Core | `{prov['package']['name']}@{prov['package']['version']}`, {isa} core SHA-256 `{prov['core']['sha256']}` |")
    src = run["source"]
    w(f"| Source | git `{src['git']['commit']}`" + (" (src/ modified)" if src["git"].get("srcDirty") else "") +
      f"; emitted with Node {src['toolchain']['node']}, TypeScript {src['toolchain']['typescript']} |")
    w(f"| Vectors | {vec['files']:,} files, {vec['tests']:,} tests; files digest `{vec['files_sha256'][:16]}…` |")
    w(f"| Harness | v{h['version']}; {h['memory']} memory; {h['steps']} step per test; host WGSL `{h['host_wgsl_sha256'][:16]}…`;"
      f" passed through (not modelled): {', '.join(_code(x) for x in h['passthrough'])} |")
    w(f"| Expected rules | `{doc['expected_rules']['file']}` |")
    a = run["adapter"]
    w(f"| GPU | {a.get('device')} ({a.get('backend_type')}, {a.get('adapter_type')}) |")
    s = run["seconds"]
    w(f"| Runtime | {s['total']} s total: GPU {s['gpu']} s in {run['dispatches']} dispatches of up to "
      f"{run['lanes_per_dispatch']:,} lanes; ledger {s['ledger']} s; parsing and other {s['parse+other']} s "
      f"({run['workers']} parser processes) |")
    w(f"| Determinism | ledger JSON SHA-256 `{digest}`; GPU output digest `{doc['gpu_digest'][:16]}…` |")
    w("")
    cov = doc.get("coverage") or {}
    if cov:
        w("## Coverage")
        w("")
        w(f"{cov['present']:,} of the {cov['reference_files']:,} reference files ran"
          + (f", plus {len(cov['extra'])} analytic or extra files ({_files(cov['extra'], 12)})" if cov["extra"] else "")
          + ".")
        w("")
        if cov["missing_by_group"]:
            w("| Group | Missing files |")
            w("|---|---|")
            for g, keys in cov["missing_by_group"].items():
                w(f"| {g} | {len(keys)}: {_files(keys, 8)} |")
            w("")
    w("## Summary")
    w("")
    arch_note, internal, group_word = WORDING.get(isa, WORDING["z80"])
    w(arch_note)
    w("")
    w("| | tests | share |")
    w("|---|---:|---:|")
    w(f"| Tests run | {t['tests']:,} | |")
    w(f"| Architectural pass, raw | {t['pass_arch']:,} | {pct(t['pass_arch'], t['tests'])} |")
    w(f"| All fields pass, raw (incl. {internal}) | {t['pass_all']:,} | {pct(t['pass_all'], t['tests'])} |")
    w(f"| Every divergence explained by an expected rule | {t['explained']:,} | {pct(t['explained'], t['tests'])} |")
    w(f"| Tests with an unexpected divergence | {t['unexpected']:,} | {pct(t['unexpected'], t['tests'])} |")
    w(f"| … of which in an architectural field | {t['unexpected_arch']:,} | {pct(t['unexpected_arch'], t['tests'])} |")
    w("")
    w(f"### By {group_word}")
    w("")
    w("| Group | Files | Tests | Arch. pass (raw) | Explained | Unexpected |")
    w("|---|---:|---:|---:|---:|---:|")
    for g, v in doc["summary"]["groups"].items():
        w(f"| {g} | {v['files']} | {v['tests']:,} | {v['pass_arch']:,} ({pct(v['pass_arch'], v['tests'])}) | "
          f"{v['explained']:,} ({pct(v['explained'], v['tests'])}) | {v['unexpected']:,} |")
    w("")
    w("### By ledger column")
    w("")
    w("Tests with at least one divergent field in the column.")
    w("")
    w("| Column | Fields | Kind | Tests diverging | Unexpected | Files |")
    w("|---|---|---|---:|---:|---:|")
    fields_by_col: dict[str, list[str]] = {}
    arch_by_col: dict[str, bool] = {}
    for f in doc["fields"]:
        fields_by_col.setdefault(f["column"], []).append(f["name"])
        arch_by_col[f["column"]] = f["architectural"]
    for c, v in doc["summary"]["columns"].items():
        w(f"| {c} | {' '.join(fields_by_col.get(c, []))} | {'architectural' if arch_by_col.get(c) else 'internal'} | "
          f"{v['diverging_tests']:,} | {v['unexpected_tests']:,} | {v['files']} |")
    w("")
    w("## Expected divergences")
    w("")
    w("Rules from the expected-rules file. A rule explains the listed bits of the listed fields, in the listed files, "
      "where its condition holds. A rule with no hits is stale (or its files are absent).")
    w("")
    w("| Rule | Files | Fields (mask) | Condition | Tests | Files hit |")
    w("|---|---|---|---|---:|---:|")
    for r in doc["rules"]:
        if isinstance(r["mask"], dict):
            fm = ", ".join(f"{f} ({r['mask'][f]})" if f in r["mask"] else f for f in r["fields"])
        else:
            fm = ", ".join(r["fields"]) + (f" ({r['mask']})" if r["mask"] else "")
        w(f"| {r['id']} | {_files(r['files'], 12)} | {fm} | {r['when'] or 'always'} | {r['hit_tests']:,} | {r['hit_files']} |")
    w("")
    for r in doc["rules"]:
        w(f"**{r['id']}.** {r['reason']} Source: {r['source']}.")
        ex = r.get("example")
        if ex:
            diffs = "; ".join(
                f"`{f}` {d['expected']} → {d['actual']}" if "expected" in d else f"`{f}` {json.dumps(d)}"
                for f, d in ex["diff"].items()
            )
            w(f"Example: `{ex['name']}` (bytes `{ex['bytes']}`): {diffs}.")
        w("")
    w("## Unexpected divergences")
    w("")
    cls = doc["unexpected_classes"]
    if not cls:
        w("None: every divergence is covered by an expected rule.")
        w("")
    for k, c in enumerate(cls, 1):
        masks = "; ".join(f"`{n}` {flag_names(m, isa, n)}" for n, m in c["unexpected_xor"].items())
        w(f"### U{k}. {c['group']}: {', '.join(c['fields'])} — {c['tests']:,} tests in {len(c['files'])} files")
        w("")
        w(f"Files: {_files(c['files'])}. Unexpected bits: {masks}.")
        w("")
        w("Minimal reproducer (fewest divergent fields, then fewest differing bits):")
        w("")
        L.extend(_reproducer(c["reproducer"], isa))
        w("")
    if analysis:
        w("## Analysis")
        w("")
        w(analysis.strip())
        w("")
    w("## Per-opcode ledger")
    w("")
    w("Files with a divergence in an architectural field or an unexpected divergence. Entries read "
      f"`field: tests [rule ids] xor`; for `{FLAG_FIELD.get(isa, 'f')}` the differing flags are named. Files whose only "
      f"divergences are in the internal columns ({internal}) are omitted here and listed in full in the JSON ledger.")
    w("")
    w("| File | Tests | Arch. pass | Unexpected | Divergent fields |")
    w("|---|---:|---:|---:|---|")
    internal_only = 0
    arch_cols = {f["name"] for f in doc["fields"] if f["architectural"]}
    for key, rec in doc["files"].items():
        arch = {n: e for n, e in rec["fields"].items() if n in arch_cols}
        if not arch and not rec["unexpected"]:
            internal_only += 1
            continue
        parts = []
        for n, e in rec["fields"].items():
            if n not in arch_cols and not e["unexpected"]:
                continue
            rules = ",".join(e["rules"]) or "—"
            x = flag_names(e["xor"], isa, n) if n in (FLAG_FIELD.get(isa, "f"), "mem", "ports", "bus") else hex(e["xor"])
            u = f" **{e['unexpected']} unexpected**" if e["unexpected"] else ""
            parts.append(f"{n}: {e['diverging']} [{rules}] {x}{u}")
        mapped = "; mapped " + ", ".join(f"{k} {v}" for k, v in rec["mapped"].items()) if rec["mapped"] else ""
        w(f"| `{key}` | {rec['tests']} | {rec['pass_arch']} | {rec['unexpected']} | {'; '.join(parts) or '—'}{mapped} |")
    w("")
    w(f"{internal_only} further files diverge only in the internal columns.")
    w("")
    return "\n".join(L)
